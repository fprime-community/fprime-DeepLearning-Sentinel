"""Streaming reads from R2, checksum-verified, sharded-first.

Two decisions are baked in here.

**One whole-object GET per object.** Measured on a real shard
(`ch_channel_74.part000.parquet`, 45.5 MiB, 10 row groups): reading *the parquet
footer alone* through a ranged GET costs one Class B, and reading the *entire
object* also costs one Class B. A ranged read is therefore footer plus N row
groups -- at least two operations against one. Egress is free, so ranged reads
buy memory and wall-clock and never operations. They exist here as an explicit
opt-in for narrow slices, with the extra operations counted, and are never the
default.

**Integrity is per object, never per channel.** A sharded manifest entry carries
``key: null`` *and* ``sha256: ''``, so a loader that checks the parent's checksum
checks nothing at all. :class:`~sentinel_eval.catalog.Channel` already flattens
both forms to a tuple of objects, each with its own digest, and every one is
verified on arrival.

The time column is named ``t_anon`` the moment it leaves this module. ESA-ADB
timestamps are anonymised mission time -- scaled by an undisclosed factor and
shifted to start 2000-01-01 -- so they are not UTC and no elapsed duration
derived from them is a real duration. Naming makes that hard to forget: there is
no ``.timestamp`` attribute anywhere downstream to reach for by habit.
"""
from __future__ import annotations

import hashlib
import io
from dataclasses import dataclass
from typing import Protocol

import numpy as np
import pyarrow.parquet as pq

from .catalog import Catalog, Channel, StoredObject
from .errors import IntegrityError


class ObjectSource(Protocol):
    """Anything that can hand over an object's bytes by key.

    The seam that lets the whole harness run offline: :class:`R2Source` fetches
    from the bucket, ``synthetic.SyntheticSource`` serves generated bytes, and
    every module above this one is identical in both cases.
    """

    def get(self, key: str) -> bytes: ...


@dataclass
class R2Source:
    """The real bucket. Every read is one counted, verified GetObject."""

    client: object
    bucket: str

    def get(self, key: str) -> bytes:
        # (!) IMPORTED HERE, NOT AT MODULE SCOPE. `sentinel_data.r2` imports
        # boto3 and botocore at ITS module scope, so a top-level import here put
        # a cloud client into the import graph of everything that reads a
        # channel -- including `sentinel_toolkit`'s offline selftest, which
        # serves `synthetic.SyntheticSource` and never touches a bucket. D80.
        # This is the only line in the harness that needs the real transport,
        # and it is the only one that pays for it.
        from sentinel_data import r2

        return r2.get_bytes(self.client, self.bucket, key)


@dataclass(frozen=True)
class Series:
    """One channel as raw arrays, still on its own irregular sampling grid.

    Deliberately not a DataFrame, and deliberately not called ``timestamp``.
    """

    channel: Channel
    t_anon: np.ndarray   # datetime64[ns], anonymised mission time
    value: np.ndarray

    def __len__(self) -> int:
        return int(self.t_anon.shape[0])


def fetch_object(source: ObjectSource, obj: StoredObject, *, verify: bool = True) -> bytes:
    """One object's bytes, checked against the checksum the manifest carries."""
    blob = source.get(obj.key)
    if verify and obj.sha256:
        got = hashlib.sha256(blob).hexdigest()
        if got != obj.sha256:
            raise IntegrityError(
                f"{obj.key}: sha256 mismatch\n  manifest {obj.sha256}\n  fetched  {got}"
            )
    if obj.nbytes and len(blob) != obj.nbytes:
        raise IntegrityError(
            f"{obj.key}: {len(blob):,} bytes, manifest says {obj.nbytes:,}"
        )
    return blob


def read_table(source: ObjectSource, obj: StoredObject, *, columns=None, verify: bool = True):
    """One object as a pyarrow Table."""
    table = pq.read_table(io.BytesIO(fetch_object(source, obj, verify=verify)), columns=columns)
    if obj.rows and table.num_rows != obj.rows:
        raise IntegrityError(
            f"{obj.key}: {table.num_rows:,} rows, manifest says {obj.rows:,}"
        )
    return table


@dataclass(frozen=True)
class Executions:
    """When each telecommand fired, still on its own irregular grid.

    Three columns rather than a :class:`Series`' two: many commands share one
    object, so each execution carries the id it belongs to.
    """

    telecommand_id: np.ndarray   # str
    t_anon: np.ndarray           # datetime64[ns], anonymised mission time
    value: np.ndarray

    def __len__(self) -> int:
        return int(self.t_anon.shape[0])

    def ids(self) -> list[str]:
        return sorted(set(self.telecommand_id.tolist()))

    def of(self, wanted) -> "Executions":
        keep = np.isin(self.telecommand_id, list(wanted))
        return Executions(self.telecommand_id[keep], self.t_anon[keep], self.value[keep])


def read_telecommands(source: ObjectSource, obj: StoredObject, *, verify: bool = True
                      ) -> Executions:
    """A mission's telecommand executions. One object, one Class B."""
    table = read_table(source, obj,
                       columns=["telecommand_id", "timestamp", "value"], verify=verify)
    return Executions(
        telecommand_id=np.asarray(table.column("telecommand_id").to_pylist()),
        t_anon=table.column("timestamp").to_numpy(zero_copy_only=False),
        value=table.column("value").to_numpy(zero_copy_only=False),
    )


def read_channel(source: ObjectSource, channel: Channel, *, verify: bool = True) -> Series:
    """One channel, shards concatenated in time order, as a :class:`Series`.

    Written against `mission1/channel_74` -- a sharded channel -- first, so the
    two-object path is the one that was proved and the single-object path is the
    degenerate case rather than the other way round.
    """
    parts_t: list[np.ndarray] = []
    parts_v: list[np.ndarray] = []

    for obj in channel.objects:          # already time-ordered by the catalog
        table = read_table(source, obj, columns=["timestamp", "value"], verify=verify)
        parts_t.append(table.column("timestamp").to_numpy(zero_copy_only=False))
        parts_v.append(_values_of(table))
        del table

    t_anon = parts_t[0] if len(parts_t) == 1 else np.concatenate(parts_t)
    value = parts_v[0] if len(parts_v) == 1 else np.concatenate(parts_v)
    del parts_t, parts_v

    if channel.rows and t_anon.shape[0] != channel.rows:
        raise IntegrityError(
            f"{channel}: {t_anon.shape[0]:,} rows across {len(channel.objects)} object(s), "
            f"manifest says {channel.rows:,}"
        )
    if t_anon.shape[0] > 1 and not _is_sorted(t_anon):
        raise IntegrityError(
            f"{channel}: timestamps are not monotonic after concatenating "
            f"{len(channel.objects)} object(s) -- shard order is wrong"
        )
    return Series(channel=channel, t_anon=t_anon, value=value)


def read_annotation(source: ObjectSource, catalog: Catalog, name: str, *, verify: bool = True):
    """An annotation table, as a pyarrow Table. Small; whole-object always."""
    return read_table(source, catalog.annotation(name), verify=verify)


# --------------------------------------------------------------------------
def _values_of(table) -> np.ndarray:
    """Values in their native dtype. Categorical channels arrive as strings."""
    column = table.column("value")
    try:
        return column.to_numpy(zero_copy_only=False)
    except Exception:
        return np.asarray(column.to_pylist(), dtype=object)


def _is_sorted(a: np.ndarray) -> bool:
    return bool(np.all(a[:-1] <= a[1:]))
